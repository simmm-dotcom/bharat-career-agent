# ==========================================
# GEMINI RETRY
# ==========================================

def generate_with_retry(contents, max_attempts=3):

    delay = 2

    for attempt in range(1, max_attempts + 1):

        try:

            print(
                f"Gemini request attempt "
                f"{attempt}/{max_attempts}"
            )

            response = client.models.generate_content(
                model=model_name,
                contents=contents
            )

            return response

        except Exception as error:

            error_text = str(error)

            print(
                f"Gemini attempt {attempt} failed:",
                error_text
            )

            # 429 is normally quota/rate limiting.
            # Do not repeatedly hammer the API.
            if (
                "429" in error_text
                or "RESOURCE_EXHAUSTED" in error_text
            ):

                raise error

            temporary_error = (
                "503" in error_text
                or "UNAVAILABLE" in error_text
                or "500" in error_text
                or "502" in error_text
                or "504" in error_text
                or "INTERNAL" in error_text
            )

            if not temporary_error:

                raise error

            if attempt == max_attempts:

                raise error

            print(
                f"Temporary Gemini problem. "
                f"Retrying in {delay} seconds..."
            )

            time.sleep(delay)

            delay *= 2


# ==========================================
# CHECK WHETHER FALLBACK SHOULD BE USED
# ==========================================

def should_use_fallback(error):

    error_text = str(error)

    return (
        "429" in error_text
        or "RESOURCE_EXHAUSTED" in error_text
        or "503" in error_text
        or "UNAVAILABLE" in error_text
        or "500" in error_text
        or "502" in error_text
        or "504" in error_text
    )


# ==========================================
# NORMAL ERROR HANDLING
# ==========================================

def ai_error_response(error):

    error_text = str(error)

    print(
        "Gemini API Error:",
        error_text
    )

    if (
        "404" in error_text
        or "NOT_FOUND" in error_text
    ):

        return jsonify({
            "error":
            "The configured Gemini model is unavailable. "
            "Please check GEMINI_MODEL in your .env file."
        }), 500

    if (
        "401" in error_text
        or "403" in error_text
        or "API_KEY" in error_text.upper()
    ):

        return jsonify({
            "error":
            "There is a problem with the Gemini API key. "
            "Please check your .env file."
        }), 500

    return jsonify({
        "error":
        "The AI service is unavailable right now. "
        "Please try again later."
    }), 500


