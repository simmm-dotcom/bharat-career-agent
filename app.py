@app.route(
    "/analyze-resume",
    methods=["POST"]
)
def analyze_resume():

    if "resume" not in request.files:

        return jsonify({
            "error":
            "Please select a resume."
        }), 400


    resume = request.files[
        "resume"
    ]


    if resume.filename == "":

        return jsonify({
            "error":
            "Please select a PDF resume."
        }), 400


    if not resume.filename.lower().endswith(
        ".pdf"
    ):

        return jsonify({
            "error":
            "Only PDF resumes are supported."
        }), 400


    # Check file size

    resume.seek(
        0,
        os.SEEK_END
    )

    file_size = resume.tell()

    resume.seek(0)


    if file_size > 5 * 1024 * 1024:

        return jsonify({
            "error":
            "The resume must be smaller than 5 MB."
        }), 400


    file_path = None


    try:

        os.makedirs(
            "uploads",
            exist_ok=True
        )


        file_path = os.path.join(
            "uploads",
            "student_resume.pdf"
        )


        resume.save(
            file_path
        )


        uploaded_file = client.files.upload(
            file=file_path
        )


        # Wait for Gemini file processing

        for attempt in range(30):

            file_info = client.files.get(
                name=uploaded_file.name
            )

            state = str(
                file_info.state
            )

            print(
                "Resume processing:",
                state
            )


            if "ACTIVE" in state:
                break


            if "FAILED" in state:

                return jsonify({
                    "error":
                    "Gemini could not process the resume."
                }), 500


            time.sleep(1)


        else:

            return jsonify({
                "error":
                "The resume took too long to process."
            }), 500


        prompt = """
You are Bharat Career Agent.

Analyze the uploaded student's resume.

Only use information actually present in the resume.

Never invent qualifications, experience, projects,
certifications or skills.

Use these sections:

## Resume Summary

## Strong Points

## Skills Detected

## Recommended Skills

## Suitable Career Roles

## Project Recommendations

Suggest 3 practical projects.

## Internship Preparation

## Resume Improvements

## Next Steps

Give exactly 3 practical next actions.

Keep everything beginner-friendly and practical.
"""


        response = generate_with_retry(
            [
                uploaded_file,
                prompt
            ]
        )


        return jsonify({
            "analysis":
            response.text,
            "source":
            "gemini"
        })


    except Exception as error:

        print(
            "Resume Analysis Error:",
            error
        )


        if should_use_fallback(
            error
        ):

            return jsonify({
                "analysis":
                """
## ⚠️ Resume Analysis Temporarily Unavailable

Gemini is currently rate-limited or temporarily unavailable.

Your PDF was received by Bharat Career Agent, but the system
will **not generate fake resume feedback** without actually
analyzing the document.

### Demo Mode

The Resume Analyzer normally performs:

- Resume summary
- Skill detection
- Strength analysis
- Missing skill recommendations
- Suitable career role suggestions
- Project recommendations
- Internship preparation advice
- Resume improvement suggestions

Please retry the resume analysis when the Gemini service
becomes available again.
""",
                "source":
                "fallback"
            })


        return ai_error_response(
            error
        )


    finally:

        if (
            file_path
            and os.path.exists(
                file_path
            )
        ):

            try:

                os.remove(
                    file_path
                )

            except Exception:

                pass


